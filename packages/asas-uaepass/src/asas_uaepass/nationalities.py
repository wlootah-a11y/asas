def normalize_code(value: object) -> str | None:
    """The code if UAE PASS's list has it, else None. Case and surrounding
    spaces are forgiven; ``XXX`` and anything unknown are None."""
    if not isinstance(value, str):
        return None
    code = value.strip().upper()
    return code if code in NATIONALITIES else None


def name(code: str, *, language: str = "en") -> str:
    """The country's name in English or Arabic, for display."""
    english, arabic = NATIONALITIES[code]
    return arabic if language == "ar" else english
